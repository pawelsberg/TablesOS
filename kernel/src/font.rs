//! Two bitmap typefaces + UTF-8 glyph lookup.
//!
//! The UI spec requires UTF-8 support. The rendering pipeline is fully UTF-8:
//! text is decoded to Unicode scalar values and each is looked up here. The
//! kernel ships **two** 8×8 faces so different parts of the HUD can be set in
//! different type — see [`Font`]:
//!
//! * [`Font::Body`] — the public-domain `font8x8` *basic* block (ASCII
//!   0x20..=0x7E): a clean, legible mono used for data rows, values and key
//!   hints. The workhorse "console" face.
//! * [`Font::Display`] — a hand-drawn **bold geometric all-caps** face used
//!   for the title bar, telemetry, section headers, buttons and the status
//!   line. Letters are folded to upper-case (a display-type convention) and
//!   any code point it doesn't define falls back to the body face, so the two
//!   always stay layout-compatible (both are 8×8, one cell advance).
//!
//! Every code point with no bitmap in either face renders as the replacement
//! box, so non-ASCII text displays without corrupting layout.

pub const GLYPH_W: usize = 8;
pub const GLYPH_H: usize = 8;

/// Which typeface to render a run of text in. See the module docs.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Font {
    Body,
    Display,
}

/// Replacement glyph (a hollow box) for code points with no bitmap.
const NOTDEF: [u8; 8] = [0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00];

/// Non-ASCII glyphs the application actually renders (arrows, dashes,
/// ellipsis). Kept exhaustive with the code points used in `ui.rs` so nothing
/// shows as the replacement box. Bit 0 is the left-most pixel.
#[rustfmt::skip]
mod extra {
    pub const EM_DASH:   [u8; 8] = [0x00,0x00,0x00,0x00,0xFF,0x00,0x00,0x00]; // U+2014 —
    pub const ELLIPSIS:  [u8; 8] = [0x00,0x00,0x00,0x00,0x00,0xDB,0xDB,0x00]; // U+2026 …
    pub const ARROW_L:   [u8; 8] = [0x00,0x04,0x02,0xFD,0xFD,0x02,0x04,0x00]; // U+2190 ←
    pub const ARROW_U:   [u8; 8] = [0x18,0x3C,0x7E,0x18,0x18,0x18,0x18,0x18]; // U+2191 ↑
    pub const ARROW_R:   [u8; 8] = [0x00,0x20,0x40,0xBF,0xBF,0x40,0x20,0x00]; // U+2192 →
    pub const ARROW_D:   [u8; 8] = [0x18,0x18,0x18,0x18,0x18,0x7E,0x3C,0x18]; // U+2193 ↓
    pub const ARROW_RET: [u8; 8] = [0x04,0x04,0x24,0xFC,0x20,0x00,0x00,0x00]; // U+2BA1 ⮡
}

/// Return the 8×8 bitmap for `ch` in `font`. Each byte is one row; bit 0 is
/// the left-most pixel.
pub fn glyph(font: Font, ch: char) -> &'static [u8; 8] {
    match font {
        Font::Body => body_glyph(ch),
        Font::Display => display_glyph(ch),
    }
}

/// The body face: `font8x8` basic, with the shared non-ASCII extras.
fn body_glyph(ch: char) -> &'static [u8; 8] {
    let c = ch as u32;
    if (0x20..0x7F).contains(&c) {
        return &BASIC[(c - 0x20) as usize];
    }
    match c {
        0x2014 => &extra::EM_DASH,
        0x2026 => &extra::ELLIPSIS,
        0x2190 => &extra::ARROW_L,
        0x2191 => &extra::ARROW_U,
        0x2192 => &extra::ARROW_R,
        0x2193 => &extra::ARROW_D,
        0x2BA1 => &extra::ARROW_RET,
        _ => &NOTDEF,
    }
}

/// The display face: bold geometric capitals + digits + the punctuation that
/// shows up in chrome. Lower-case folds to upper-case; anything undefined
/// falls back to the body face so layout never breaks.
fn display_glyph(ch: char) -> &'static [u8; 8] {
    let mut c = ch as u32;
    if (0x61..=0x7A).contains(&c) {
        c -= 0x20; // a–z → A–Z
    }
    if (0x41..=0x5A).contains(&c) {
        return &DISP_AZ[(c - 0x41) as usize];
    }
    if (0x30..=0x39).contains(&c) {
        return &DISP_09[(c - 0x30) as usize];
    }
    match c {
        0x2F => &DISP_SLASH,
        0x2B => &DISP_PLUS,
        0x2D => &DISP_HYPHEN,
        0x3A => &DISP_COLON,
        0x2E => &DISP_DOT,
        0x2C => &DISP_COMMA,
        0x5B => &DISP_LBRACK,
        0x5D => &DISP_RBRACK,
        0x28 => &DISP_LPAREN,
        0x29 => &DISP_RPAREN,
        0x3D => &DISP_EQ,
        0x21 => &DISP_BANG,
        0x2014 => &DISP_EMDASH,
        _ => body_glyph(ch), // space, arrows, rare punctuation
    }
}

