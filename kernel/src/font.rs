//! Two bitmap typefaces + UTF-8 glyph lookup.
//!
//! The UI spec requires UTF-8 support. The rendering pipeline is fully UTF-8:
//! text is decoded to Unicode scalar values and each is looked up here. The
//! kernel ships **two** 8×8 faces so different parts of the HUD can be set in
//! different type — see [`Font`]:
//!
//! * [`Font::Body`] — the public-domain `font8x8` *basic* block (ASCII
//!   0x20..=0x7E): a clean, legible mono used for data rows, values and key
//!   hints. The workhorse "console" face.
//! * [`Font::Display`] — a hand-drawn **bold geometric all-caps** face used
//!   for the title bar, telemetry, section headers, buttons and the status
//!   line. Letters are folded to upper-case (a display-type convention) and
//!   any code point it doesn't define falls back to the body face, so the two
//!   always stay layout-compatible (both are 8×8, one cell advance).
//!
//! Every code point with no bitmap in either face renders as the replacement
//! box, so non-ASCII text displays without corrupting layout.

pub const GLYPH_W: usize = 8;
pub const GLYPH_H: usize = 8;

/// Which typeface to render a run of text in. See the module docs.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Font {
    Body,
    Display,
}

